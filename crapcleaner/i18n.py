def localized_category_field(category, field: str, language: str) -> str:
    """Translate category metadata, with a safe Chinese fallback for new plugins.

    Third-party or newly added categories may introduce descriptions after the
    catalog was shipped.  Their names still identify the item, so the fallback
    keeps the explanation readable in Chinese instead of leaking a whole English
    paragraph into an otherwise translated page.
    """
    raw = str(getattr(category, field, "") or "")
    if not raw or language != "zh_CN":
        return raw
    translated = translate(raw, language)
    if translated != raw:
        return translated
    name = localized_category_name(str(getattr(category, "name", "此分类")), language)
    if field == "description":
        return f"{name}相关的缓存、临时文件或维护数据。"
    if field == "what_it_contains":
        return f"此分类中的 {name} 相关本地文件。"
    if field == "why_it_grows":
        return "相关应用运行、构建或更新时会持续生成这些数据。"
    if field == "why_safe_to_delete":
        return "仅处理可重新生成或由应用维护的数据；项目源文件、设置和重要用户文件不会被处理。"
    if field == "regeneration_behavior":
        return "相关应用下次运行时会按需重新生成这些数据。"
    return translated


