def _source_text(widget: QWidget, value: str) -> str:
    source = widget.property("ccSourceText")
    previous = widget.property("ccTranslatedText")
    # A view may update a label after the last translation (for example with a
    # scan result).  In that case the new value is the next English source string.
    if isinstance(source, str) and isinstance(previous, str) and value != previous:
        source = value
        widget.setProperty("ccSourceText", source)
    elif not isinstance(source, str):
        widget.setProperty("ccSourceText", value)
        return value
    return source


def _retranslate_widget(widget: QWidget, language: str) -> None:
    if widget.property("ccSkipTranslation"):
        return
    if isinstance(widget, QAbstractButton):
        current = widget.text()
        translated = translate(_source_text(widget, current), language)
        widget.setText(translated)
        widget.setProperty("ccTranslatedText", translated)
    elif isinstance(widget, QLabel):
        current = widget.text()
        translated = translate(_source_text(widget, current), language)
        widget.setText(translated)
        widget.setProperty("ccTranslatedText", translated)
    elif isinstance(widget, QLineEdit):
        placeholder = widget.placeholderText()
        if placeholder:
            translated = translate(_source_text(widget, placeholder), language)
            widget.setPlaceholderText(translated)
            widget.setProperty("ccTranslatedText", translated)
    elif isinstance(widget, QComboBox):
        for index in range(widget.count()):
            source = widget.itemData(index, Qt.UserRole + 1)
            if not isinstance(source, str):
                source = widget.itemText(index)
                widget.setItemData(index, source, Qt.UserRole + 1)
            widget.setItemText(index, translate(source, language))


def retranslate_tree(root: QObject, language: str) -> None:
    """Retranslate visible widget text below *root*.

    The function is intentionally best-effort: dynamic values such as sizes and
    paths are left alone, while all static labels retain their original English
    source in ``ccSourceText`` so toggling back and forth is lossless.
    """

    if isinstance(root, QWidget):
        _retranslate_widget(root, language)
    for child in root.findChildren(QWidget):
        _retranslate_widget(child, language)
